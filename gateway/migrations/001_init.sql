-- 001_init.sql: core schema for the SMS gateway.
--
-- Conventions
--   * Money is BIGINT micro-units (1 USD = 1,000,000 micros). No floats, anywhere.
--   * Every invariant that matters for money or message state is enforced here,
--     by a constraint or a unique index, not only in application code.
--   * Timestamps are timestamptz, written with clock_timestamp() where the order
--     of rows inside one transaction matters.

-- ---------------------------------------------------------------------------
-- Tenants
-- ---------------------------------------------------------------------------
CREATE TABLE tenants (
    id                      uuid PRIMARY KEY,
    slug                    text NOT NULL UNIQUE,
    name                    text NOT NULL,
    -- sha256(api_key) in hex. The key itself is never stored.
    api_key_hash            text NOT NULL UNIQUE,
    api_key_prefix          text NOT NULL,
    currency                text NOT NULL DEFAULT 'USD',
    opening_balance_micros  bigint NOT NULL CHECK (opening_balance_micros >= 0),
    -- The last line of defence for "the balance never goes below zero".
    balance_micros          bigint NOT NULL CHECK (balance_micros >= 0),
    callback_url            text,
    webhook_secret          text,
    created_at              timestamptz NOT NULL DEFAULT now()
);

-- Round-robin pointer for fair dispatch. Kept out of `tenants` on purpose:
-- it is updated on every claim, and `tenants` holds the balance row that every
-- charge locks. Two hot paths, two rows.
CREATE TABLE dispatch_cursor (
    tenant_id       uuid PRIMARY KEY REFERENCES tenants (id) ON DELETE CASCADE,
    last_served_at  timestamptz NOT NULL DEFAULT '-infinity'
);

-- ---------------------------------------------------------------------------
-- Prices: longest matching destination prefix wins.
-- ---------------------------------------------------------------------------
CREATE TABLE prices (
    prefix                    text PRIMARY KEY CHECK (prefix ~ '^\+[1-9][0-9]{0,5}$'),
    country                   text NOT NULL,
    price_per_segment_micros  bigint NOT NULL CHECK (price_per_segment_micros > 0)
);

-- ---------------------------------------------------------------------------
-- Messages. The row is also the queue entry (see DESIGN.md, "Queue").
-- ---------------------------------------------------------------------------
CREATE TABLE messages (
    id                  uuid PRIMARY KEY,           -- UUIDv7, generated by the API
    tenant_id           uuid NOT NULL REFERENCES tenants (id),
    batch_id            uuid,
    client_ref          text,
    to_number           text NOT NULL,
    sender_id           text NOT NULL,
    body                text NOT NULL,
    encoding            text NOT NULL CHECK (encoding IN ('GSM7', 'UCS2')),
    segments            integer NOT NULL CHECK (segments > 0),
    price_prefix        text NOT NULL,
    unit_price_micros   bigint NOT NULL CHECK (unit_price_micros > 0),
    cost_micros         bigint NOT NULL,
    status              text NOT NULL CHECK (status IN (
                            'ACCEPTED', 'QUEUED', 'SUBMITTED',
                            'DELIVERED', 'UNDELIVERED', 'EXPIRED', 'FAILED')),
    -- Submit attempts started so far. Also the fencing token for a lease.
    attempts            integer NOT NULL DEFAULT 0 CHECK (attempts >= 0),
    -- Attempts whose outcome we could not observe (timeout, lost worker).
    -- > 0 means the carrier may have accepted this message more than once.
    ambiguous_attempts  integer NOT NULL DEFAULT 0 CHECK (ambiguous_attempts >= 0),
    -- Visibility time. A QUEUED message can be claimed when this is in the past.
    -- A claim pushes it forward by the lease, so a crashed worker's message
    -- becomes visible again by itself.
    next_attempt_at     timestamptz NOT NULL DEFAULT now(),
    locked_by           text,
    carrier_id          text,
    failure_reason      text,
    created_at          timestamptz NOT NULL DEFAULT now(),
    submitted_at        timestamptz,
    finalized_at        timestamptz,
    CONSTRAINT messages_cost_is_segments_times_price
        CHECK (cost_micros = segments * unit_price_micros)
);

-- The dispatch queue: only QUEUED rows, per tenant, oldest visibility first.
CREATE INDEX messages_dispatch_idx
    ON messages (tenant_id, next_attempt_at, id)
    WHERE status = 'QUEUED';

-- Listing: newest first, keyset-paginated on (created_at, id).
CREATE INDEX messages_tenant_created_idx ON messages (tenant_id, created_at DESC, id DESC);
CREATE INDEX messages_tenant_status_idx  ON messages (tenant_id, status, created_at DESC, id DESC);
CREATE INDEX messages_created_idx        ON messages (created_at DESC, id DESC);
CREATE INDEX messages_status_idx         ON messages (status, created_at DESC, id DESC);
CREATE INDEX messages_client_ref_idx     ON messages (tenant_id, client_ref) WHERE client_ref IS NOT NULL;

-- ---------------------------------------------------------------------------
-- Status history. One row per status a message has entered.
-- ---------------------------------------------------------------------------
CREATE TABLE message_events (
    id           bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    message_id   uuid NOT NULL REFERENCES messages (id) ON DELETE CASCADE,
    tenant_id    uuid NOT NULL REFERENCES tenants (id),
    status       text NOT NULL,
    occurred_at  timestamptz NOT NULL DEFAULT clock_timestamp(),
    detail       jsonb NOT NULL DEFAULT '{}'::jsonb,
    -- Status only moves forward, so a message enters each status at most once.
    -- This index turns that rule into something the database refuses to break.
    CONSTRAINT message_events_once_per_status UNIQUE (message_id, status)
);

-- ---------------------------------------------------------------------------
-- Submit attempts. Written BEFORE the HTTP call (outcome NULL = in flight),
-- so a crash leaves evidence that an attempt may have reached the carrier.
-- ---------------------------------------------------------------------------
CREATE TABLE submit_attempts (
    id           bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    message_id   uuid NOT NULL REFERENCES messages (id) ON DELETE CASCADE,
    attempt_no   integer NOT NULL CHECK (attempt_no > 0),
    worker_id    text NOT NULL,
    started_at   timestamptz NOT NULL DEFAULT clock_timestamp(),
    finished_at  timestamptz,
    outcome      text CHECK (outcome IN (
                     'ACCEPTED',      -- 200 with a carrier_id
                     'RATE_LIMITED',  -- 429: not accepted, retry
                     'UNAVAILABLE',   -- 503: not accepted, retry
                     'REJECTED',      -- 4xx: permanent, never retry
                     'TIMEOUT',       -- no answer: carrier MAY have accepted
                     'ABANDONED')),   -- lease expired with no result: MAY have accepted
    http_status  integer,
    carrier_id   text,
    error        text,
    CONSTRAINT submit_attempts_once UNIQUE (message_id, attempt_no)
);

-- A carrier_id identifies exactly one accepted attempt. DLRs are matched here.
CREATE UNIQUE INDEX submit_attempts_carrier_id_idx
    ON submit_attempts (carrier_id) WHERE carrier_id IS NOT NULL;

-- ---------------------------------------------------------------------------
-- Delivery receipts as received from the carrier (an inbox).
-- ---------------------------------------------------------------------------
CREATE TABLE dlr_receipts (
    id                 bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    carrier_id         text NOT NULL,
    status             text NOT NULL CHECK (status IN ('DELIVRD', 'UNDELIV', 'EXPIRED')),
    carrier_timestamp  timestamptz NOT NULL,
    received_at        timestamptz NOT NULL DEFAULT clock_timestamp(),
    message_id         uuid REFERENCES messages (id) ON DELETE CASCADE,
    -- PENDING: no submit response with this carrier_id yet (early DLR), or never (orphan).
    -- APPLIED: moved the message to its final status.
    -- IGNORED: the message was already final.
    disposition        text NOT NULL DEFAULT 'PENDING'
                           CHECK (disposition IN ('PENDING', 'APPLIED', 'IGNORED')),
    applied_at         timestamptz,
    -- A repeated DLR hits this index and is dropped: no row, no effect.
    CONSTRAINT dlr_receipts_dedupe UNIQUE (carrier_id, status)
);

CREATE INDEX dlr_receipts_pending_idx ON dlr_receipts (carrier_id) WHERE disposition = 'PENDING';
CREATE INDEX dlr_receipts_message_idx ON dlr_receipts (message_id) WHERE message_id IS NOT NULL;

-- ---------------------------------------------------------------------------
-- Ledger. balance = opening_balance - sum(amount_micros).
-- ---------------------------------------------------------------------------
CREATE TABLE ledger_entries (
    id                    bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    tenant_id             uuid NOT NULL REFERENCES tenants (id),
    message_id            uuid NOT NULL REFERENCES messages (id),
    kind                  text NOT NULL CHECK (kind IN ('CHARGE', 'REFUND')),
    -- Signed as a debit: a charge is positive, a refund is negative.
    amount_micros         bigint NOT NULL,
    balance_after_micros  bigint NOT NULL CHECK (balance_after_micros >= 0),
    created_at            timestamptz NOT NULL DEFAULT clock_timestamp(),
    CONSTRAINT ledger_sign_matches_kind CHECK (
        (kind = 'CHARGE' AND amount_micros > 0) OR
        (kind = 'REFUND' AND amount_micros < 0)),
    -- "Never charge twice" and "never refund twice", enforced by the database.
    CONSTRAINT ledger_once_per_message_kind UNIQUE (message_id, kind)
);

CREATE INDEX ledger_tenant_idx ON ledger_entries (tenant_id, id);

-- ---------------------------------------------------------------------------
-- Idempotency keys. Written in the same transaction as the messages and the
-- charge, so "one key -> one set of messages -> one charge" is atomic.
-- ---------------------------------------------------------------------------
CREATE TABLE idempotency_keys (
    tenant_id        uuid NOT NULL REFERENCES tenants (id) ON DELETE CASCADE,
    key              text NOT NULL CHECK (length(key) BETWEEN 1 AND 255),
    request_hash     text NOT NULL,
    response_status  integer NOT NULL,
    response_body    jsonb NOT NULL,
    created_at       timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (tenant_id, key)
);

-- ---------------------------------------------------------------------------
-- Tenant webhooks: a transactional outbox, one delivery per final message.
-- ---------------------------------------------------------------------------
CREATE TABLE webhook_deliveries (
    id               uuid PRIMARY KEY,
    tenant_id        uuid NOT NULL REFERENCES tenants (id),
    message_id       uuid NOT NULL REFERENCES messages (id) ON DELETE CASCADE,
    url              text NOT NULL,
    payload          jsonb NOT NULL,
    status           text NOT NULL DEFAULT 'PENDING'
                         CHECK (status IN ('PENDING', 'DELIVERED', 'DEAD')),
    attempts         integer NOT NULL DEFAULT 0,
    next_attempt_at  timestamptz NOT NULL DEFAULT now(),
    last_http_status integer,
    last_error       text,
    created_at       timestamptz NOT NULL DEFAULT clock_timestamp(),
    delivered_at     timestamptz,
    -- A message reaches a final state once, so it gets one webhook.
    CONSTRAINT webhook_once_per_message UNIQUE (message_id)
);

CREATE INDEX webhook_due_idx
    ON webhook_deliveries (tenant_id, next_attempt_at)
    WHERE status = 'PENDING';
